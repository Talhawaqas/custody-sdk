// src/competitive.js
//
// Competitive Expansion SOW (SDK-001): thin, stateless REST clients for the organization-scoped public API (/api/public/v1/*, Bearer inaya_... key).
// Same per-call {baseUrl, apiKey, ...} style as TrustPlatform: no hidden config, no singleton. Namespaces:
//   Shares, FileRequests, Governance, Devices, Compliance (evidence + audit verify), Webhooks (receiver-side signature verification).
//
// WHAT IS DELIBERATELY NOT HERE
//   Secure Chat, Contacts and Secure Notes are end-to-end encrypted: their keys live in a person's browser or device and are never sent to the server, so a
//   Bearer API key cannot read or write them and no wrapper can honestly be offered. Likewise a file request cannot be CREATED over the API (its key pair
//   must be generated by a person's browser); it can be listed, inspected and revoked. No call here ever returns file content or a private key.
//   Feature-flagged areas answer with a 403/404 and an explanatory error while the feature is off for the organization.

import { InayaValidationError, InayaNetworkError, translateError } from "./errors.js";

const base = (baseUrl) => { if (!baseUrl) throw new InayaValidationError("baseUrl is required."); return baseUrl.replace(/\/$/, ""); };
const need = (v, name) => { if (!v) throw new InayaValidationError(`${name} is required.`); };
const e1 = encodeURIComponent;
const enc = new TextEncoder();
const hex = (buf) => [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, "0")).join("");
async function hmacHex(secret, data) {
  const key = await globalThis.crypto.subtle.importKey("raw", enc.encode(secret), { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
  return hex(await globalThis.crypto.subtle.sign("HMAC", key, enc.encode(data)));
}
function sameString(a, b) { if (a.length !== b.length) return false; let d = 0; for (let i = 0; i < a.length; i++) d |= a.charCodeAt(i) ^ b.charCodeAt(i); return d === 0; }
const qs = (o = {}) => { const p = new URLSearchParams(); for (const [k, v] of Object.entries(o)) if (v !== undefined && v !== null && v !== "") p.set(k, String(v)); const s = p.toString(); return s ? `?${s}` : ""; };

async function call({ baseUrl, apiKey, method = "GET", path, body }) {
  const root = base(baseUrl);
  need(apiKey, "apiKey (an inaya_... key)");
  const headers = { Authorization: `Bearer ${apiKey}` };
  if (body !== undefined) headers["Content-Type"] = "application/json";
  let res;
  try { res = await fetch(`${root}/api/public/v1/${path}`, { method, headers, ...(body !== undefined ? { body: JSON.stringify(body) } : {}) }); }
  catch (err) { throw translateError(err, "inaya-api"); }
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw Object.assign(new InayaNetworkError(data.error || `Request failed (${res.status}).`, { operation: "inaya-api" }), { status: res.status, code: data.code });
  return data;
}

export const Shares = {
  /** Every share in the organization. status: active | expired | revoked | exhausted. */
  list: ({ baseUrl, apiKey, status, documentId, limit, before }) => call({ baseUrl, apiKey, path: `shares${qs({ status, documentId, limit, before })}` }),
  /** A link share. `expiresAt` is required (ISO). Returns { shareId, token, share }; the token is shown once. */
  createLink: ({ baseUrl, apiKey, documentId, expiresAt, options }) => { need(documentId, "documentId"); need(expiresAt, "expiresAt"); return call({ baseUrl, apiKey, method: "POST", path: "shares", body: { documentId, expiresAt, options } }); },
  /** A share with a person already in the organization. permission: view | download | edit (see the share policy). */
  createMember: ({ baseUrl, apiKey, documentId, memberEmail, permission, expiresAt }) => { need(documentId, "documentId"); need(memberEmail, "memberEmail"); need(permission, "permission"); return call({ baseUrl, apiKey, method: "POST", path: "shares", body: { documentId, memberEmail, permission, expiresAt } }); },
  accessEvents: ({ baseUrl, apiKey, shareId, limit, before }) => { need(shareId, "shareId"); return call({ baseUrl, apiKey, path: `shares/${e1(shareId)}${qs({ limit, before })}` }); },
  revoke: ({ baseUrl, apiKey, shareId }) => { need(shareId, "shareId"); return call({ baseUrl, apiKey, method: "DELETE", path: `shares/${e1(shareId)}` }); },
};

