export const Webhooks = {
  /**
   * Receiver-side verification of an Inaya webhook. Pass the RAW request body string and the x-inaya-signature header ("t=<ts>,v1=<hex>[,v1=<hex>]").
   * During a secret rotation the header carries two v1 values; either matches. Rejects anything older than `toleranceSeconds` (default 300) to stop replays.
   * Resolves true / false; a bad signature never throws (a missing secret or body does).
   */
  async verify({ secret, rawBody, signatureHeader, toleranceSeconds = 300, now = Date.now() }) {
    need(secret, "secret"); need(typeof rawBody === "string" ? rawBody : null, "rawBody (string)");
    const parts = String(signatureHeader || "").split(",").map((s) => s.trim());
    const t = parts.find((p) => p.startsWith("t="))?.slice(2);
    const sigs = parts.filter((p) => p.startsWith("v1=")).map((p) => p.slice(3));
    if (!t || !sigs.length || !/^\d+$/.test(t)) return false;
    if (Math.abs(now / 1000 - Number(t)) > toleranceSeconds) return false;
    const expected = await hmacHex(secret, `${t}.${rawBody}`);
    return sigs.some((x) => sameString(x, expected));
  },
};
